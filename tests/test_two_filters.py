def _load(name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_all_codes_enumerate_the_population() -> None:
    codes = all_codes(3)
    assert codes.shape == (64, 3)
    assert len({tuple(r) for r in codes}) == 64


def test_string_values_match_monomials() -> None:
    rng = np.random.default_rng(0)
    n = 3
    codes = draw_inputs(50, n, rng)
    ops = {0: "X", 2: "Z"}
    got = string_values(codes, pauli_bits(n, ops)[None, :])[:, 0]
    np.testing.assert_allclose(got, monomial_values(codes, ops) / 2.0)
    y_string = np.zeros(2 * n, dtype=bool)
    y_string[1] = y_string[n + 1] = True  # Y on site 1
    assert not string_values(codes, y_string[None, :]).any()
    assert visible(np.stack([y_string, pauli_bits(n, ops)])).tolist() == [False, True]


def test_split_is_pythagoras_only_for_projections() -> None:
    """``total = circuit + readout + cross`` always; ``cross = 0`` iff projections."""
    rng = np.random.default_rng(1)
    phi_s = rng.normal(size=(400, 8))
    phi_f = phi_s[:, :3] @ rng.normal(size=(3, 3))  # Span F inside Span S
    y = phi_s @ rng.normal(size=8) + rng.normal(size=400)
    for lam in (0.0, 0.5):
        d = decompose(ridge_fit(phi_f, y, lam), ridge_fit(phi_s, y, lam), y)
        assert d.total == pytest.approx(d.circuit + d.readout + d.cross, abs=1e-12)
        if lam == 0:
            assert abs(d.cross) < 1e-12
        else:
            assert abs(d.cross) > 1e-3


def test_any_decoder_error() -> None:
    rng = np.random.default_rng(2)
    phi = rng.integers(-1, 2, size=(3000, 2))
    y = (phi[:, 0] * phi[:, 1]) ** 2 + 0.0  # a function of the features
    assert any_decoder_error(phi, y) == pytest.approx(0.0, abs=1e-12)
    lin = np.mean((y - y.mean() - ridge_fit(phi, y - y.mean(), 0.0)) ** 2) / np.var(y)
    assert lin > 0.5  # not linear in the features
    noise = rng.normal(size=3000)
    assert any_decoder_error(phi, noise) > 0.99
    assert any_decoder_error(np.zeros((10, 0)), noise[:10]) == 1.0


@pytest.mark.parametrize("seed", [0, 1, 2])
def test_clifford_split_symmetry_and_inclusion(seed: int) -> None:
    """At N = 4, on the whole population:

    - every readout string is in ``G`` (``F^(k) ⊂ Span G``);
    - the cross term vanishes at ``lambda = 0`` and the monomial terms are the
      membership indicators;
    - no decoder of any form beats 1 on a monomial outside the full-record
      group, the mid-record group, or the group generated by ``F^(k)``.
    """
    script = _load("two_filters")
    rng = np.random.default_rng(seed)
    n, t = 4, 8
    circuit = with_mask(draw_circuit(n, t, rng), rng.random((t, n)), 0.2)
    res = script.exact_sample(circuit, 3, rng)
    assert res["inclusion_violations"] == [0, 0, 0]
    assert res["S_any_outside_G_min"] == pytest.approx(1.0)
    if res["mid_any_outside_Gmid_min"] is not None:
        assert res["mid_any_outside_Gmid_min"] == pytest.approx(1.0)
    for row in res["k"]:
        assert row["mono_max_abs_cross"] < 1e-10
        assert row["mono_max_dev_circuit_indicator"] < 1e-10
        assert row["mono_max_dev_total_indicator"] < 1e-10
        assert row["mono_total"] == pytest.approx(
            row["mono_circuit"] + row["mono_readout"], abs=1e-10
        )
        if row["any_outside_closure_min"] is not None:
            assert row["any_outside_closure_min"] == pytest.approx(1.0)
        for name in ("dense", "deg1", "basis"):
            d0 = row[name][0]
            assert abs(d0["cross"]) < 1e-10


def test_two_filter_scripts_run_and_plot(tmp_path: Path) -> None:
    script = _load("two_filters")
    assert script.ring_range(np.array([1, 0, 0, 1], dtype=bool)) == 2
    ex = script.run_exact(4, [0.1, 0.3], 2, 2, 0)
    (tmp_path / "exact_N4_s0.json").write_text(json.dumps(ex))
    loc = script.run_locality(8, [0.1, 0.3], 2, 2, 0)
    (tmp_path / "locality_N8_s0.json").write_text(json.dumps(loc))
    for row in loc["per_p"]:
        fam = row["families"]["Z"]
        assert 0 <= fam["circuit"]["mean"] <= 1
        r1, r2 = (r["mean"] for r in fam["readout"])
        assert r2 <= r1 + 1e-12  # more parities, less readout loss
        assert all(v["max"] == 0 for v in row["inclusion_violations"])
    sh = script.run_shots([0.3], 1, 2, [4], 0)
    (tmp_path / "shots_N4_s0.json").write_text(json.dumps(sh))
    _load("plot_two_filters").main([str(tmp_path)])
    for name in ("two_filters_additivity", "two_filters_locality"):
        assert (tmp_path / "figures" / f"{name}.png").is_file()
