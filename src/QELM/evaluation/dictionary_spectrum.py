"""Spectrum of the effect dictionary across the MIPT (issue #356).

The dictionary is the set of input functions that the readout of the
record can represent at ``K = inf``: the span of the effects ``E_m``,
written on the Pauli (Fourier) basis. Two ways to look at its spectrum.

**Clifford: weight enumerator of the group of the effect.** For a
stabilizer circuit, ``E_m = Tr(E_m) 2^-r sum_{g in G} s_g(m) g^T`` with
``G`` a group of ``2^r`` Pauli strings that does not depend on ``m``
(:mod:`QELM.evaluation.clifford_ridge`). The dictionary is ``Span G`` and
its natural spectrum is the histogram ``N(l)`` of the Hamming weights
``l = |g|`` (the number of sites where ``g != I``):

- ``sum_l N(l) = 2^r`` exactly, ``r = N`` with the final readout and
  ``r = N - Delta`` without it;
- the strings without ``Y`` (visible to the angle encoding) give the
  eigenvalues of the record covariance ``F`` of issue #334: ``F`` is
  diagonal on them with eigenvalue ``w_g = 2^-|g|``, so the visible
  histogram ``N_vis(l)`` *is* the spectrum of ``F``, level by level.

The group is enumerated by doubling on bit masks (one ``uint64`` per string
for ``x`` and one for ``z``), so ``N = 20`` takes ``2^20`` strings.

**Haar: spectrum of F and degree profiles.** Without the group structure,
the spectrum is the sorted eigenvalue list of
``F = E_m[v(m) v(m)^T]``, ``v_a = sqrt(w_a) c_a(m) / c_0(m)`` (the squared
singular values of the Born-weighted dictionary matrix, rows the records,
columns the Pauli modes). Two degree profiles reduce to ``N_vis(l)`` for a
Clifford circuit and extend it to Haar:

- the span profile ``P(l) = sum_{|a| = l} Pi_aa``, with ``Pi`` the
  orthogonal projector on the span (coordinates ``f_a``); it sums to the
  rank of the span;
- the Born profile ``N_F(l) = sum_{|a| = l} F_aa / w_l = sum_{|a| = l}
  E_m[(c_a / c_0)^2]``; each mode counts with its mean squared reading
  amplitude, in ``[0, 1]``.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np
from scipy.special import comb

from QELM.evaluation.clifford_ridge import GroupBasis
from QELM.evaluation.fourier import monomial_degrees

MAX_ENUMERATED_RANK = 24


def _masks(rows: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """``x`` and ``z`` bit masks of ``[x | z]`` rows, site ``i`` on bit ``i``."""
    a = np.asarray(rows, dtype=bool)
    n = a.shape[1] // 2
    if n > 64:
        raise ValueError(f"At most 64 sites fit in one mask, got {n}.")
    bits = np.uint64(1) << np.arange(n, dtype=np.uint64)
    x = (a[:, :n].astype(np.uint64) * bits).sum(axis=1, dtype=np.uint64)
    z = (a[:, n:].astype(np.uint64) * bits).sum(axis=1, dtype=np.uint64)
    return x, z


def weight_enumerator(generators: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Weight histograms of the group generated by ``generators``.

    Args:
        generators: ``[x | z]`` rows, shape ``(k, 2 N)``; they need not be
            independent (they are reduced first).

    Returns:
        ``(all_strings, visible)``: integer arrays of length ``N + 1``;
        entry ``l`` counts the elements of weight ``l`` (identity at
        ``l = 0``), all of them or only those without ``Y``.
        ``all_strings.sum() == 2^r`` with ``r`` the rank of the group.
    """
    gens = np.asarray(generators, dtype=bool)
    n = gens.shape[1] // 2
    rows = GroupBasis(gens).rows if gens.shape[0] else gens
    if rows.shape[0] > MAX_ENUMERATED_RANK:
        raise ValueError(f"2^{rows.shape[0]} elements is too many to enumerate.")
    gx, gz = _masks(rows)
    x = np.zeros(1, dtype=np.uint64)
    z = np.zeros(1, dtype=np.uint64)
    for a, b in zip(gx, gz, strict=True):
        x = np.concatenate([x, x ^ a])
        z = np.concatenate([z, z ^ b])
    weight = np.bitwise_count(x | z)
    visible = np.bitwise_count(x & z) == 0
    all_strings = np.bincount(weight, minlength=n + 1)
    vis = np.bincount(weight[visible], minlength=n + 1)
    return all_strings.astype(np.int64), vis.astype(np.int64)


def random_strings_null(n: int, rank: int) -> tuple[np.ndarray, np.ndarray]:
    """Mean histograms of ``2^rank`` uniformly random Pauli strings.

    ``2^rank C(N, l) 3^l / 4^N`` for all strings (peak at ``l = 3N/4``) and
    ``2^rank C(N, l) 2^l / 4^N`` for those without ``Y`` (peak at
    ``l = 2N/3``). A Haar-random stabilizer group of rank ``r`` has the
    same mean, up to the identity, which is always in it.
    """
    ell = np.arange(n + 1)
    c = comb(n, ell)
    scale = 2.0**rank / 4.0**n
    return scale * c * 3.0**ell, scale * c * 2.0**ell


def product_z_reference(n: int) -> np.ndarray:
    """Histogram ``C(N, l)`` of the ``2^N`` ``Z`` strings (every site measured)."""
    return np.asarray(comb(n, np.arange(n + 1)))


def mean_weight(hist: np.ndarray) -> float:
    """Mean weight of a histogram, identity excluded."""
    h = np.asarray(hist, dtype=float)
    ell = np.arange(h.size)
    tot = h[1:].sum()
    return float((ell[1:] * h[1:]).sum() / tot) if tot > 0 else 0.0


# ---------------------------------------------------------------------------
# Haar: degree profiles of the span and of F
# ---------------------------------------------------------------------------


def degree_profile(diagonal: np.ndarray, n: int) -> np.ndarray:
    """``sum_{|a| = l} d_a`` for the ``3^n`` monomials, ``l = 0 .. n``."""
    d = np.asarray(diagonal, dtype=float)
    if d.size != 3**n:
        raise ValueError(f"Expected 3^{n} = {3**n} entries, got {d.size}.")
    return np.bincount(monomial_degrees(n), weights=d, minlength=n + 1)


def span_profile(span: np.ndarray, n: int) -> np.ndarray:
    """Degree profile of the projector on an orthonormal span (rows ``f_a``).

    Sums to the number of rows. For a Clifford circuit it is the visible
    histogram ``N_vis(l)`` of the group of the effect.
    """
    s = np.asarray(span, dtype=float)
    return degree_profile(np.sum(s**2, axis=0), n)


def born_profile(v: np.ndarray, n: int) -> np.ndarray:
    """``N_F(l) = sum_{|a| = l} E_m[(c_a / c_0)^2]`` from rows of conditional means.

    Args:
        v: Rows ``v_a(m) = sqrt(w_a) c_a(m) / c_0(m)``
            (:func:`QELM.evaluation.ridge_spectrum.conditional_means`),
            Born-drawn records.
        n: Number of sites.
    """
    degrees = monomial_degrees(n)
    f_diag = np.mean(np.asarray(v, dtype=float) ** 2, axis=0)
    return degree_profile(f_diag * 2.0**degrees, n)


def effective_ranks(
    mu: np.ndarray, thresholds: Sequence[float]
) -> dict[str, float | list[int]]:
    """Summaries of a spectrum ``mu`` (non-negative, any order).

    Returns:
        ``above``: number of ``mu > lambda`` for each threshold (list);
        ``participation``: ``(sum mu)^2 / sum mu^2``;
        ``entropy``: ``exp(H)`` of ``mu / sum mu``.
    """
    m = np.clip(np.asarray(mu, dtype=float), 0.0, None)
    tot = float(m.sum())
    if tot <= 0:
        return {"above": [0] * len(thresholds), "participation": 0.0, "entropy": 0.0}
    q = m[m > 0] / tot
    return {
        "above": [int(np.sum(m > lam)) for lam in thresholds],
        "participation": float(tot**2 / np.sum(m**2)),
        "entropy": float(np.exp(-np.sum(q * np.log(q)))),
    }
